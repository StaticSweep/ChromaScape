package com.chromascape.web.recording.service;

import static org.junit.jupiter.api.Assertions.*;

import com.fasterxml.jackson.databind.ObjectMapper;
import java.time.LocalDateTime;
import java.util.List;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

/** Unit tests for {@link RecordingSessionMetadataService}. */
class RecordingSessionMetadataServiceTest {

  private RecordingSessionMetadataService service;

  @BeforeEach
  void setUp() {
    service = new RecordingSessionMetadataService(new ObjectMapper());
  }

  // --- parseTags ---

  @Test
  void parseTags_null_returnsEmptyList() {
    assertTrue(service.parseTags(null).isEmpty());
  }

  @Test
  void parseTags_blank_returnsEmptyList() {
    assertTrue(service.parseTags("").isEmpty());
    assertTrue(service.parseTags("   ").isEmpty());
  }

  @Test
  void parseTags_validJson_returnsTags() {
    assertEquals(List.of("a", "b"), service.parseTags("[\"a\",\"b\"]"));
  }

  @Test
  void parseTags_invalidJson_returnsEmptyList() {
    assertTrue(service.parseTags("not json").isEmpty());
  }

  // --- serializeTags ---

  @Test
  void serializeTags_null_returnsNull() {
    assertNull(service.serializeTags(null));
  }

  @Test
  void serializeTags_empty_returnsNull() {
    assertNull(service.serializeTags(List.of()));
  }

  @Test
  void serializeTags_values_returnsJson() {
    assertEquals("[\"alpha\",\"beta\"]", service.serializeTags(List.of("alpha", "beta")));
  }

  // --- normalizeTags ---

  @Test
  void normalizeTags_null_returnsEmptyList() {
    assertTrue(service.normalizeTags(null).isEmpty());
  }

  @Test
  void normalizeTags_trimsAndDedupes() {
    assertEquals(
        List.of("Alpha", "Beta"),
        service.normalizeTags(List.of("  Alpha ", "alpha", "  Beta  ", "BETA")));
  }

  @Test
  void normalizeTags_dropsEmpty() {
    assertEquals(List.of("valid"), service.normalizeTags(List.of("", "  ", "valid")));
  }

  // --- validateTags ---

  @Test
  void validateTags_withinLimit_passes() {
    assertDoesNotThrow(() -> service.validateTags(List.of("a", "b")));
  }

  @Test
  void validateTags_exceedsMax_throws() {
    List<String> tooMany =
        java.util.stream.IntStream.range(0, 21).mapToObj(i -> "tag" + i).toList();
    assertThrows(IllegalArgumentException.class, () -> service.validateTags(tooMany));
  }

  @Test
  void validateTags_tagTooLong_throws() {
    assertThrows(
        IllegalArgumentException.class, () -> service.validateTags(List.of("x".repeat(33))));
  }

  // --- validateReplayName ---

  @Test
  void validateReplayName_null_passes() {
    assertDoesNotThrow(() -> service.validateReplayName(null));
  }

  @Test
  void validateReplayName_tooLong_throws() {
    assertThrows(IllegalArgumentException.class, () -> service.validateReplayName("x".repeat(161)));
  }

  @Test
  void validateReplayName_withinLimit_passes() {
    assertDoesNotThrow(() -> service.validateReplayName("x".repeat(160)));
  }

  // --- computeDisplayName ---

  @Test
  void computeDisplayName_customName_returnsCustomName() {
    assertEquals(
        "My Replay", service.computeDisplayName("My Replay", "acct", "script", "2025-01-01 12:00"));
  }

  @Test
  void computeDisplayName_blankCustom_fallsBack() {
    assertEquals(
        "script - acct - 2025-01-01 12:00",
        service.computeDisplayName("  ", "acct", "script", "2025-01-01 12:00"));
  }

  @Test
  void computeDisplayName_noCustom_autoGenerated() {
    assertEquals(
        "script - acct - 2025-01-01 12:00",
        service.computeDisplayName(null, "acct", "script", "2025-01-01 12:00"));
  }

  @Test
  void computeDisplayName_allNull_returnsUnnamed() {
    assertEquals("Unnamed Recording", service.computeDisplayName(null, null, null, null));
  }

  // --- formatStartTime ---

  @Test
  void formatStartTime_null_returnsNull() {
    assertNull(service.formatStartTime(null));
  }

  @Test
  void formatStartTime_value_returnsFormatted() {
    LocalDateTime dt = LocalDateTime.of(2025, 6, 15, 14, 30);
    assertEquals("2025-06-15 14:30", service.formatStartTime(dt));
  }
}
