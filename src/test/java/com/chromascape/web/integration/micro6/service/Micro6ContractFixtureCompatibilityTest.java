package com.chromascape.web.integration.micro6.service;

import static org.assertj.core.api.Assertions.assertThat;

import com.chromascape.web.integration.micro6.service.Micro6CatalogV2Contract.ValidationResult;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Pattern;
import org.junit.jupiter.api.Test;

/**
 * Cross-component fixture compatibility for the exact files generated by Micro6. The current
 * producer fixtures also preserve a known regression where schema-bearing task fields make full
 * and lightweight catalog hashes differ. ChromaScape rejects those payloads until Micro6 restores
 * the single catalog identity required by its health and registry protocol.
 */
class Micro6ContractFixtureCompatibilityTest {
  private static final ObjectMapper MAPPER = new ObjectMapper();
  private static final Pattern SHA256_HEX = Pattern.compile("^sha256:[0-9a-f]{64}$");

  @Test
  void modeSpecificProducerCatalogHashesAreRejected() throws Exception {
    assertCatalogRejected("catalog-lightweight.json", false);
    assertCatalogRejected("catalog-full-ready.json", true);
    assertCatalogRejected("catalog-full-not-applicable.json", true);
    assertCatalogRejected("catalog-full-error.json", true);
  }

  @Test
  void healthFixturesSatisfyTheHealthContract() throws Exception {
    assertHealthValid("health-bootstrap.json", "NOT_AVAILABLE", true);
    assertHealthValid("health-generating.json", "GENERATING", true);
    assertHealthValid("health-available.json", "AVAILABLE", true);
  }

  @Test
  void fixtureManifestChecksumsMatchGeneratedFiles() throws Exception {
    Map<String, String> manifest = loadManifest();
    for (String name :
        List.of(
            "catalog-lightweight.json",
            "catalog-full-ready.json",
            "catalog-full-not-applicable.json",
            "catalog-full-error.json",
            "health-bootstrap.json",
            "health-generating.json",
            "health-available.json")) {
      String expected = manifest.get(name);
      assertThat(expected).as("fixture %s must be present in the manifest", name).isNotBlank();
      assertThat(sha256Hex(fixtureBytes(name)))
          .as("fixture %s must match the producer-generated checksum", name)
          .isEqualTo(expected);
    }
  }

  private void assertCatalogRejected(String name, boolean full) throws Exception {
    JsonNode payload = fixtureJson(name);
    ValidationResult result =
        full
            ? Micro6CatalogV2Contract.validateFull(payload)
            : Micro6CatalogV2Contract.validateLightweight(payload);
    assertThat(result.valid()).as("fixture %s must fail closed", name).isFalse();
    assertThat(result.reasons())
        .as("fixture %s must expose the mode-specific catalog hash regression", name)
        .contains("catalog_hash_mismatch");
  }

  private void assertHealthValid(String name, String expectedSchemaBundleState, boolean expectAlive)
      throws Exception {
    JsonNode health = fixtureJson(name);
    assertThat(health.path("executor_instance_id").asText()).isNotBlank();
    assertThat(health.path("process_alive").asBoolean()).isEqualTo(expectAlive);
    assertThat(health.path("catalog_version").asText()).isEqualTo("2");
    assertThat(health.path("catalog_hash").asText()).matches(SHA256_HEX.pattern());
    String state = health.path("schema_bundle_state").asText();
    assertThat(state).isEqualTo(expectedSchemaBundleState);
    assertThat(List.of("NOT_AVAILABLE", "GENERATING", "AVAILABLE", "ERROR"))
        .as("schema_bundle_state must be a contract state")
        .contains(state);
    if ("AVAILABLE".equals(state)) {
      assertThat(health.path("schema_bundle_hash").asText()).matches(SHA256_HEX.pattern());
    } else {
      JsonNode bundle = health.get("schema_bundle_hash");
      assertThat(bundle == null || bundle.isNull())
          .as("schema_bundle_hash must be absent/null when not AVAILABLE")
          .isTrue();
    }
  }

  private Map<String, String> loadManifest() throws Exception {
    Map<String, String> manifest = new LinkedHashMap<>();
    for (String line :
        new String(fixtureBytes("fixtures-manifest.sha256"), StandardCharsets.UTF_8).split("\\R")) {
      if (line.isBlank()) {
        continue;
      }
      String[] parts = line.trim().split("\\s+", 2);
      if (parts.length == 2) {
        manifest.put(parts[1], parts[0]);
      }
    }
    return manifest;
  }

  private JsonNode fixtureJson(String name) throws Exception {
    return MAPPER.readTree(fixtureBytes(name));
  }

  private byte[] fixtureBytes(String name) throws Exception {
    InputStream stream = getClass().getClassLoader().getResourceAsStream("micro6-fixtures/" + name);
    assertThat(stream).as("fixture %s must exist in ChromaScape test resources", name).isNotNull();
    return stream.readAllBytes();
  }

  private String sha256Hex(byte[] bytes) throws Exception {
    MessageDigest digest = MessageDigest.getInstance("SHA-256");
    byte[] hash = digest.digest(bytes);
    StringBuilder hex = new StringBuilder(hash.length * 2);
    for (byte b : hash) {
      hex.append(Character.forDigit((b >> 4) & 0xF, 16));
      hex.append(Character.forDigit(b & 0xF, 16));
    }
    return hex.toString();
  }
}
