package com.chromascape.web.debug.tickdebugger.service;

import com.chromascape.web.debug.tickdebugger.entity.TickLog;
import com.chromascape.web.debug.tickdebugger.entity.TickLogRepository;
import com.chromascape.web.debug.tickdebugger.entity.TimelineMarker;
import com.chromascape.web.debug.tickdebugger.entity.TimelineMarkerRepository;
import com.fasterxml.jackson.databind.JsonNode;
import java.util.ArrayList;
import java.util.List;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/**
 * Service for generating and managing timeline markers.
 *
 * <p>Auto-generates markers for significant events like errors, damage taken, prayer mistakes,
 * deaths, and kills.
 */
@Service
public class TimelineMarkerService {

  private static final Logger log = LoggerFactory.getLogger(TimelineMarkerService.class);

  private final TimelineMarkerRepository markerRepository;
  private final TickLogRepository logRepository;

  public TimelineMarkerService(
      TimelineMarkerRepository markerRepository, TickLogRepository logRepository) {
    this.markerRepository = markerRepository;
    this.logRepository = logRepository;
  }

  /**
   * Generate auto-markers for a session.
   *
   * @param sessionId the session ID
   * @return list of generated markers
   */
  @Transactional
  public List<TimelineMarker> generateMarkers(String sessionId) {
    List<TimelineMarker> markers = new ArrayList<>();

    // 1. Error markers
    markers.addAll(generateErrorMarkers(sessionId));

    // 2. Damage markers
    markers.addAll(generateDamageMarkers(sessionId));

    // 3. Death markers
    markers.addAll(generateDeathMarkers(sessionId));

    // 4. Kill markers
    markers.addAll(generateKillMarkers(sessionId));

    // 5. Prayer mistake markers (correlate damage with prayer state)
    markers.addAll(generatePrayerMistakeMarkers(sessionId));

    // Save all markers
    return markerRepository.saveAll(markers);
  }

  /** Generate error markers from ERROR level logs. */
  private List<TimelineMarker> generateErrorMarkers(String sessionId) {
    List<TimelineMarker> markers = new ArrayList<>();

    List<TickLog> errorLogs =
        logRepository.findBySessionIdAndSeverityIgnoreCaseOrderByTickAsc(sessionId, "Error");

    for (TickLog errorLog : errorLogs) {
      // Check if marker already exists for this log
      if (markerRepository.findBySessionIdAndTick(sessionId, errorLog.getTick()).stream()
          .anyMatch(
              m -> "ERROR".equals(m.getMarkerType()) && errorLog.getId().equals(m.getLogId()))) {
        continue;
      }

      TimelineMarker marker =
          new TimelineMarker(
              sessionId,
              errorLog.getTick(),
              "ERROR",
              "Error: " + (errorLog.getSubsystem() != null ? errorLog.getSubsystem() : "System"));

      marker.setSeverity("Error");
      marker.setDescription(errorLog.getMessage());
      marker.setLogId(errorLog.getId());
      marker.setIsAutoGenerated(true);

      markers.add(marker);
    }

    log.info("Generated {} error markers for session {}", markers.size(), sessionId);
    return markers;
  }

  /** Generate damage markers from damage-related logs. */
  private List<TimelineMarker> generateDamageMarkers(String sessionId) {
    List<TimelineMarker> markers = new ArrayList<>();

    List<TickLog> damageLogs =
        logRepository.findBySessionIdAndMessageContainingIgnoreCaseOrderByTickAsc(
            sessionId, "damage taken");

    for (TickLog damageLog : damageLogs) {
      if (markerRepository.findBySessionIdAndTick(sessionId, damageLog.getTick()).stream()
          .anyMatch(m -> "DAMAGE".equals(m.getMarkerType()))) {
        continue;
      }

      TimelineMarker marker =
          new TimelineMarker(sessionId, damageLog.getTick(), "DAMAGE", "Damage Taken");

      marker.setSeverity("Warn");
      marker.setDescription(extractDamageAmount(damageLog));
      marker.setLogId(damageLog.getId());
      marker.setIsAutoGenerated(true);

      markers.add(marker);
    }

    log.info("Generated {} damage markers for session {}", markers.size(), sessionId);
    return markers;
  }

  /** Generate death markers (HP reaches 0). */
  private List<TimelineMarker> generateDeathMarkers(String sessionId) {
    List<TimelineMarker> markers = new ArrayList<>();

    List<TickLog> deathLogs =
        logRepository.findBySessionIdAndMessageContainingIgnoreCaseOrderByTickAsc(
            sessionId, "died");

    for (TickLog deathLog : deathLogs) {
      if (markerRepository.findBySessionIdAndTick(sessionId, deathLog.getTick()).stream()
          .anyMatch(m -> "DEATH".equals(m.getMarkerType()))) {
        continue;
      }

      TimelineMarker marker = new TimelineMarker(sessionId, deathLog.getTick(), "DEATH", "Death");

      marker.setSeverity("Error");
      marker.setDescription("Player died");
      marker.setLogId(deathLog.getId());
      marker.setIsAutoGenerated(true);

      markers.add(marker);
    }

    log.info("Generated {} death markers for session {}", markers.size(), sessionId);
    return markers;
  }

  /** Generate kill markers from kill-related logs. */
  private List<TimelineMarker> generateKillMarkers(String sessionId) {
    List<TimelineMarker> markers = new ArrayList<>();

    List<TickLog> killLogs =
        logRepository.findBySessionIdAndMessageContainingIgnoreCaseOrderByTickAsc(
            sessionId, "killed");

    for (TickLog killLog : killLogs) {
      if (markerRepository.findBySessionIdAndTick(sessionId, killLog.getTick()).stream()
          .anyMatch(m -> "KILL".equals(m.getMarkerType()))) {
        continue;
      }

      TimelineMarker marker = new TimelineMarker(sessionId, killLog.getTick(), "KILL", "Kill");

      marker.setSeverity("Success");
      marker.setDescription(extractKillTarget(killLog));
      marker.setLogId(killLog.getId());
      marker.setIsAutoGenerated(true);

      markers.add(marker);
    }

    log.info("Generated {} kill markers for session {}", markers.size(), sessionId);
    return markers;
  }

  /**
   * Generate prayer mistake markers by correlating damage with wrong prayer.
   *
   * <p>This is a simplified implementation. A more sophisticated version would analyze the prayer
   * state at each damage tick and compare against incoming attack types.
   */
  private List<TimelineMarker> generatePrayerMistakeMarkers(String sessionId) {
    List<TimelineMarker> markers = new ArrayList<>();

    // Find damage logs that might indicate prayer mistakes
    // Look for patterns like "damage taken" with "magic" while using protect from melee
    List<TickLog> damageLogs =
        logRepository.findBySessionIdAndMessageContainingIgnoreCaseOrderByTickAsc(
            sessionId, "damage taken");

    for (TickLog damageLog : damageLogs) {
      String message = damageLog.getMessage().toLowerCase();

      // Simple heuristics for prayer mistakes
      boolean isMagicDamage = message.contains("magic") || message.contains("mage");
      boolean isRangedDamage = message.contains("ranged") || message.contains("range");
      boolean isMeleeDamage = message.contains("melee");

      // Check if there's a nearby prayer log that suggests wrong prayer
      List<TickLog> nearbyLogs =
          logRepository.findBySessionIdAndTickBetweenOrderByTickAsc(
              sessionId, Math.max(0, damageLog.getTick() - 5), damageLog.getTick() + 5);

      boolean hasWrongPrayer = false;
      String wrongPrayerType = null;

      for (TickLog nearbyLog : nearbyLogs) {
        String nearbyMessage = nearbyLog.getMessage().toLowerCase();

        if ((isMagicDamage && nearbyMessage.contains("protect from melee"))
            || (isRangedDamage && nearbyMessage.contains("protect from magic"))
            || (isMeleeDamage
                && (nearbyMessage.contains("protect from magic")
                    || nearbyMessage.contains("protect from missiles")))) {
          hasWrongPrayer = true;
          wrongPrayerType = isMagicDamage ? "Magic" : isRangedDamage ? "Ranged" : "Melee";
          break;
        }
      }

      if (hasWrongPrayer) {
        if (markerRepository.findBySessionIdAndTick(sessionId, damageLog.getTick()).stream()
            .anyMatch(m -> "PRAYER".equals(m.getMarkerType()))) {
          continue;
        }

        TimelineMarker marker =
            new TimelineMarker(sessionId, damageLog.getTick(), "PRAYER", "Wrong Prayer");

        marker.setSeverity("Warn");
        marker.setDescription("Took " + wrongPrayerType + " damage with wrong prayer");
        marker.setLogId(damageLog.getId());
        marker.setIsAutoGenerated(true);

        markers.add(marker);
      }
    }

    log.info("Generated {} prayer mistake markers for session {}", markers.size(), sessionId);
    return markers;
  }

  /** Extract damage amount from log details. */
  private String extractDamageAmount(TickLog log) {
    if (log.getDetails() != null) {
      JsonNode details = log.getDetails();
      if (details.has("damage")) {
        return "Damage: " + details.get("damage").asText();
      }
    }

    // Try to extract from message
    String message = log.getMessage();
    if (message.matches(".*\\d+.*damage.*")) {
      return message;
    }

    return "Damage taken";
  }

  /** Extract kill target from log details. */
  private String extractKillTarget(TickLog log) {
    if (log.getDetails() != null) {
      JsonNode details = log.getDetails();
      if (details.has("target")) {
        return "Killed: " + details.get("target").asText();
      }
    }

    // Try to extract from message
    String message = log.getMessage();
    if (message.toLowerCase().contains("killed")) {
      return message;
    }

    return "Kill";
  }

  /**
   * Create a manual marker.
   *
   * @param sessionId the session ID
   * @param tick the tick number
   * @param label the marker label
   * @param description optional description
   * @return the created marker
   */
  @Transactional
  public TimelineMarker createManualMarker(
      String sessionId, long tick, String label, String description) {
    TimelineMarker marker = new TimelineMarker(sessionId, tick, "MANUAL", label);
    marker.setDescription(description);
    marker.setIsAutoGenerated(false);

    return markerRepository.save(marker);
  }

  /** Get all markers for a session. */
  public List<TimelineMarker> getMarkers(String sessionId) {
    return markerRepository.findBySessionIdOrderByTickAsc(sessionId);
  }

  /** Delete all markers for a session. */
  @Transactional
  public void deleteMarkers(String sessionId) {
    markerRepository.deleteBySessionId(sessionId);
  }
}
