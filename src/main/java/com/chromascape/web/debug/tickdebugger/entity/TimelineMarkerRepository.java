package com.chromascape.web.debug.tickdebugger.entity;

import com.chromascape.web.debug.tickdebugger.dto.SessionCountProjection;
import java.util.List;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;
import org.springframework.stereotype.Repository;

/** Repository for accessing {@link TimelineMarker} entities. */
@Repository
public interface TimelineMarkerRepository extends JpaRepository<TimelineMarker, Long> {

  /** Find all markers for a session, ordered by tick. */
  List<TimelineMarker> findBySessionIdOrderByTickAsc(String sessionId);

  /** Find markers for a specific tick. */
  List<TimelineMarker> findBySessionIdAndTick(String sessionId, Long tick);

  /** Find markers by type for a session. */
  List<TimelineMarker> findBySessionIdAndMarkerTypeOrderByTickAsc(
      String sessionId, String markerType);

  /** Find auto-generated markers for a session. */
  List<TimelineMarker> findBySessionIdAndIsAutoGeneratedTrueOrderByTickAsc(String sessionId);

  /** Find manually created markers for a session. */
  List<TimelineMarker> findBySessionIdAndIsAutoGeneratedFalseOrderByTickAsc(String sessionId);

  /** Find markers for a session within a tick range. */
  List<TimelineMarker> findBySessionIdAndTickBetweenOrderByTickAsc(
      String sessionId, Long startTick, Long endTick);

  /** Find the nearest marker before a tick. */
  TimelineMarker findFirstBySessionIdAndTickLessThanOrderByTickDesc(String sessionId, Long tick);

  /** Find the nearest marker after a tick. */
  TimelineMarker findFirstBySessionIdAndTickGreaterThanOrderByTickAsc(String sessionId, Long tick);

  /** Delete all markers for a specific session. */
  void deleteBySessionId(String sessionId);

  /** Count markers for a session. */
  long countBySessionId(String sessionId);

  /** Count markers by type for a session. */
  long countBySessionIdAndMarkerType(String sessionId, String markerType);

  /** Count only failure/error markers for a session. */
  @Query(
      "SELECT COUNT(m) FROM TimelineMarker m WHERE m.sessionId = :sessionId"
          + " AND (UPPER(m.markerType) IN ('ERROR', 'DAMAGE', 'DEATH')"
          + " OR UPPER(m.severity) = 'ERROR')")
  long countFailuresBySessionId(@Param("sessionId") String sessionId);

  /**
   * Count failure markers grouped by session ID for a list of sessions.
   *
   * @param sessionIds the sessions to count failure markers for
   * @return list of session ID/count projections
   */
  @Query(
      "SELECT m.sessionId AS sessionId, COUNT(m) AS count FROM TimelineMarker m "
          + "WHERE m.sessionId IN :sessionIds "
          + "AND (UPPER(m.markerType) IN ('ERROR', 'DAMAGE', 'DEATH') OR UPPER(m.severity) = 'ERROR') "
          + "GROUP BY m.sessionId")
  List<SessionCountProjection> countFailuresBySessionIdIn(
      @Param("sessionIds") List<String> sessionIds);
}
