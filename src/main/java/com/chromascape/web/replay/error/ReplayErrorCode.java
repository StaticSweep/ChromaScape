package com.chromascape.web.replay.error;

/**
 * Stable eligibility and error reason codes. These are part of the public API contract. Never use
 * exception message strings as API semantics.
 */
public enum ReplayErrorCode {

  // Recording / session
  RECORDING_NOT_FOUND,
  RECORDING_ARCHIVED,
  RECORDING_NOT_FINALIZED,
  DEBUG_SESSION_NOT_FOUND,
  DEBUG_SESSION_NOT_FINALIZED,

  // Tick integrity
  NO_TICK_SNAPSHOTS,
  TICK_RANGE_INVALID,
  TICK_GAP_DETECTED,
  TICK_MISMATCH,
  DUPLICATE_TICK,

  // Actions
  ACTION_SEQUENCE_INVALID,
  ACTION_QUEUE_OVERFLOW,
  ACTION_UNSUPPORTED,
  ACTION_AMBIGUOUS,
  ACTION_TARGET_UNRESOLVED,

  // Schema / version
  SCHEMA_VERSION_UNSUPPORTED,

  // Player state
  PLAYER_STATE_MISSING,
  POSITION_MISSING,
  INVENTORY_SLOT_MISSING,
  EQUIPMENT_SLOT_MISSING,

  // Curation
  CURATION_REQUIRED,
  CURATION_NOT_PUBLISHED,
  CURATION_IMMUTABLE,
  CURATION_VERSION_CONFLICT,

  // Simulation
  SIM_INITIAL_STATE_INCOMPLETE,
  SIM_INITIAL_WORLD_INCOMPLETE,

  // xRSPS
  XRSPS_CAPABILITY_UNAVAILABLE,
  XRSPS_VERSION_INCOMPATIBLE,
  XRSPS_PROTOCOL_ERROR,
  CACHE_REVISION_UNAVAILABLE,
  CONTENT_REVISION_UNAVAILABLE,
  SNAPSHOT_INCOMPATIBLE,

  // Read-only trace viewer
  TRACE_NOT_AVAILABLE,
  TRACE_CORRUPT,
  VIEWER_UNAVAILABLE,
  VIEWER_TOKEN_INVALID,
  VIEWER_TOKEN_EXPIRED,

  // Integrity
  CHECKSUM_MISMATCH,

  // Run lifecycle
  RUN_NOT_FOUND,
  RUN_IMMUTABLE,
  RUN_STATE_INVALID,
  RUN_DEADLINE_EXCEEDED,
  RUN_IDEMPOTENCY_CONFLICT,
  RUN_CONCURRENCY_LIMIT,
  ATTEMPT_STALE_FENCE,

  // Finalization failure classes
  REPORT_PREPARATION_FAILED,
  REPORT_PERSISTENCE_FAILED,
  ARTIFACT_STORAGE_UNAVAILABLE,
  ARTIFACT_PUBLICATION_FAILED,

  // Generic
  INTERNAL_ERROR,
  VALIDATION_ERROR,
}
