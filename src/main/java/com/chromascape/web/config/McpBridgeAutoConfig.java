package com.chromascape.web.config;

import java.io.File;
import java.io.IOException;
import java.nio.file.Files;
import java.util.concurrent.TimeUnit;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;

/**
 * Auto-configuration service for MCP bridge .env file generation.
 *
 * <p>Automatically detects available provider CLIs (claude, codex, opencode) and generates a
 * production-ready .env configuration file with sensible defaults. Falls back to API mode if no CLI
 * is detected and ANTHROPIC_API_KEY is available.
 */
@Component
public class McpBridgeAutoConfig {

  private static final Logger logger = LoggerFactory.getLogger(McpBridgeAutoConfig.class);

  /**
   * Generates a default .env file for the MCP bridge with auto-detected provider configuration.
   *
   * <p>Detection strategy: 1. Try codex CLI (preferred) 2. Try claude CLI 3. Try opencode CLI 4.
   * Fall back to API mode if ANTHROPIC_API_KEY is set 5. Throw exception if no provider available
   *
   * @param envFile the .env file to create
   * @throws BridgeConfigException if no provider is available or file cannot be written
   */
  public static void generateDefaultEnv(File envFile) {
    logger.info("Auto-configuring MCP bridge...");

    // Detect best available provider
    ProviderInfo provider = detectBestProvider();

    // Generate .env content
    String envContent = buildEnvContent(provider);

    // Write file
    try {
      Files.writeString(envFile.toPath(), envContent);
      logger.info("Generated .env with backend: {}, provider: {}", provider.backend, provider.name);
    } catch (IOException e) {
      throw new BridgeConfigException("Failed to write .env file: " + e.getMessage(), e);
    }
  }

  /**
   * Detects the best available provider CLI or falls back to API mode.
   *
   * @return the detected provider information
   * @throws BridgeConfigException if no provider is available
   */
  private static ProviderInfo detectBestProvider() {
    // Try Codex CLI first (preferred)
    if (isCliAvailable("codex")) {
      logger.info("Detected Codex CLI");
      return new ProviderInfo("mcp", "codex", "codex");
    }

    // Try Claude CLI
    if (isCliAvailable("claude")) {
      logger.info("Detected Claude CLI");
      return new ProviderInfo("mcp", "claude", "claude");
    }

    // Try OpenCode CLI
    if (isCliAvailable("opencode")) {
      logger.info("Detected OpenCode CLI");
      return new ProviderInfo("mcp", "opencode", "opencode");
    }

    // Fallback to API mode if ANTHROPIC_API_KEY available
    String apiKey = System.getenv("ANTHROPIC_API_KEY");
    if (apiKey != null && !apiKey.isBlank()) {
      logger.info("No provider CLI detected, using API mode");
      return new ProviderInfo("api", null, null);
    }

    // No provider available
    throw new BridgeConfigException(
        "No provider available. Install Codex CLI (npm install -g codex-cli) or Claude CLI"
            + " (https://claude.ai/download), or set ANTHROPIC_API_KEY environment variable.");
  }

  /**
   * Checks if a CLI command is available on the system PATH.
   *
   * @param command the CLI command to check (e.g., "claude", "codex")
   * @return true if the command is available and returns a valid version
   */
  private static boolean isCliAvailable(String command) {
    try {
      // Try running the command with --version flag
      Process process = new ProcessBuilder(command, "--version").redirectErrorStream(true).start();

      boolean finished = process.waitFor(5, TimeUnit.SECONDS);
      if (!finished) {
        process.destroyForcibly();
        return false;
      }

      return process.exitValue() == 0;

    } catch (Exception e) {
      // Command not found or failed to execute
      return false;
    }
  }

  /**
   * Builds the .env file content from provider information.
   *
   * @param provider the detected provider information
   * @return the .env file content as a string
   */
  private static String buildEnvContent(ProviderInfo provider) {
    StringBuilder sb = new StringBuilder();
    sb.append("# Auto-generated by ChromaScape\n");
    sb.append("# Edit this file to customize MCP bridge configuration\n\n");

    sb.append("ANALYSIS_BACKEND=").append(provider.backend).append("\n");
    sb.append("MCP_PORT=8765\n");
    sb.append("MCP_DEFAULT_MODEL=claude-opus-4-6\n");
    sb.append("MCP_LOG_LEVEL=info\n");
    sb.append("ALLOWED_ORIGINS=http://localhost:8090\n\n");

    if ("mcp".equals(provider.backend)) {
      sb.append("# MCP Configuration\n");
      sb.append("MCP_SERVER_COMMAND=node\n");
      sb.append("MCP_SERVER_ARGS_JSON=[\"wrapper/server.js\"]\n");
      sb.append("MCP_INFERENCE_TOOL=analyze\n");
      sb.append("MCP_DEFAULT_TIMEOUT=180\n\n");

      sb.append("WRAPPER_PROVIDER=").append(provider.name).append("\n");
      sb.append("WRAPPER_")
          .append(provider.name.toUpperCase())
          .append("_COMMAND=")
          .append(provider.command)
          .append("\n");
    } else if ("api".equals(provider.backend)) {
      sb.append("# API Configuration\n");
      String apiKey = System.getenv("ANTHROPIC_API_KEY");
      if (apiKey != null) {
        sb.append("ANTHROPIC_API_KEY=").append(apiKey).append("\n");
      } else {
        sb.append("# ANTHROPIC_API_KEY=your-api-key-here\n");
      }
    }

    return sb.toString();
  }

  /** Internal class to hold provider detection results. */
  private static class ProviderInfo {
    final String backend; // "mcp" or "api"
    final String name; // "claude", "codex", "opencode", or null for API mode
    final String command; // CLI command, or null for API mode

    ProviderInfo(String backend, String name, String command) {
      this.backend = backend;
      this.name = name;
      this.command = command;
    }
  }
}
