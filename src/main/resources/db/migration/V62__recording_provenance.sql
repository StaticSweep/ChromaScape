CREATE TABLE IF NOT EXISTS recording_provenance_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recording_id varchar(100) NOT NULL, actor varchar(160) NOT NULL,
 reason varchar(500) NOT NULL, assigned_at timestamptz NOT NULL,
 context_hash varchar(71) NOT NULL, context jsonb NOT NULL
);
CREATE TABLE IF NOT EXISTS recording_tick_frames (
 session_id varchar(100) NOT NULL, sequence numeric(20,0) NOT NULL CHECK(sequence>0),
 producer_epoch uuid NOT NULL, content_hash varchar(64) NOT NULL,
 frame jsonb NOT NULL, accepted_at timestamptz NOT NULL,
 PRIMARY KEY(session_id,sequence)
);
CREATE TABLE IF NOT EXISTS recording_capture_quality (
 session_id varchar(100) PRIMARY KEY, quality jsonb NOT NULL,
 finalized boolean NOT NULL DEFAULT false, updated_at timestamptz NOT NULL
);
CREATE OR REPLACE FUNCTION recording_capture_identity_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (OLD.account_name IS NOT NULL AND NEW.account_name IS DISTINCT FROM OLD.account_name)
 OR (OLD.task_key IS NOT NULL AND NEW.task_key IS DISTINCT FROM OLD.task_key)
 OR (OLD.task_args IS NOT NULL AND NEW.task_args IS DISTINCT FROM OLD.task_args)
 OR (OLD.settings_hash IS NOT NULL AND NEW.settings_hash IS DISTINCT FROM OLD.settings_hash)
 OR (OLD.run_context IS NOT NULL AND NEW.run_context IS DISTINCT FROM OLD.run_context) THEN
  RAISE EXCEPTION 'IMMUTABLE_RECORDING_PROVENANCE' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
DO $$ BEGIN
 IF to_regclass('recording_sessions') IS NOT NULL THEN
  DROP TRIGGER IF EXISTS recording_capture_identity ON recording_sessions;
  CREATE TRIGGER recording_capture_identity BEFORE UPDATE ON recording_sessions
   FOR EACH ROW EXECUTE FUNCTION recording_capture_identity_guard();
 END IF;
END $$;
CREATE OR REPLACE FUNCTION recording_evidence_immutable_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'IMMUTABLE_CAPTURE_EVIDENCE' USING ERRCODE='23514'; END $$;
DROP TRIGGER IF EXISTS recording_frame_immutable ON recording_tick_frames;
CREATE TRIGGER recording_frame_immutable BEFORE UPDATE OR DELETE ON recording_tick_frames
 FOR EACH ROW EXECUTE FUNCTION recording_evidence_immutable_guard();
DROP TRIGGER IF EXISTS recording_audit_immutable ON recording_provenance_audit;
CREATE TRIGGER recording_audit_immutable BEFORE UPDATE OR DELETE ON recording_provenance_audit
 FOR EACH ROW EXECUTE FUNCTION recording_evidence_immutable_guard();
